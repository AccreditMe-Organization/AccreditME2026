#!/usr/bin/env node
// ACC-213 — the Sign in box refuses the same names the app does, read from the
// ONE source at build time so the two cannot drift:
//   backend/src/common/tenant/reserved-slugs.ts
//
// It takes INFRASTRUCTURE_LABELS (never a tenant AND never a sign-in host —
// what the app's own tenant-host rule refuses) and DNS_LABEL (the shape of a
// slug). It does NOT take PLATFORM_SIGN_IN_LABELS: `platform` is not a tenant,
// but platform.accreditme.app IS a real sign-in address.
//
// The backend file is TypeScript, so it is transpiled with the TypeScript
// compiler and evaluated, rather than read with a regex: the values are
// exactly what the backend exports. Writes src/generated/reserved.ts
// (gitignored). Fails, and so fails the build, if the file or either export is
// missing or empty.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const websiteRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BACKEND_RESERVED = join(websiteRoot, '..', 'backend', 'src', 'common', 'tenant', 'reserved-slugs.ts');

/** The backend module's real exports, by transpiling and evaluating it. */
export async function loadBackendReserved() {
  const source = readFileSync(BACKEND_RESERVED, 'utf8');
  const js = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const mod = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
  const labels = mod.INFRASTRUCTURE_LABELS;
  const pattern = mod.DNS_LABEL;
  if (!Array.isArray(labels) || labels.length === 0 || !labels.every((l) => typeof l === 'string')) {
    throw new Error(`INFRASTRUCTURE_LABELS missing or empty in ${BACKEND_RESERVED}`);
  }
  if (!(pattern instanceof RegExp)) throw new Error(`DNS_LABEL missing in ${BACKEND_RESERVED}`);
  return { labels: [...labels], pattern };
}

async function main() {
  const { labels, pattern } = await loadBackendReserved();
  const out = join(websiteRoot, 'src', 'generated', 'reserved.ts');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(
    out,
    [
      '// GENERATED by scripts/generate-reserved.mjs from',
      '// backend/src/common/tenant/reserved-slugs.ts — do not edit.',
      `export const RESERVED_LABELS: readonly string[] = ${JSON.stringify(labels)};`,
      `export const DNS_LABEL = new RegExp(${JSON.stringify(pattern.source)});`,
      '',
    ].join('\n'),
  );
  console.log(`generate-reserved — ${labels.length} reserved labels and the DNS label pattern written`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => {
    console.error(`generate-reserved — ${err.message}`);
    process.exit(1);
  });
}
